/**
 * Multi-provider AI adapter, CLAUDE.md §9, design-spec §12.
 *
 * The guardrail that makes this safe to attach to a teaching tool:
 *
 *   Layer A (symbolic) is the source of truth. It is deterministic TypeScript
 *   and it never asks a model anything.
 *   Layer B (this file) only ever RE-EXPLAINS Layer A's verified content.
 *
 * So the model is handed the node's authored text plus the numbers the toy
 * model already computed, and is told in the system prompt that it may not
 * introduce facts or do arithmetic. The mechanics can't be corrupted by a loose
 * answer because they were calculated, not spoken.
 *
 * Key handling: held in memory for the page session only. Never written to
 * localStorage, never bundled, never sent anywhere except the provider the user
 * chose. Browser-side keys are visible in devtools, the UI says so plainly.
 */

export type ProviderId = 'anthropic' | 'openai' | 'openrouter' | 'google' | 'lmstudio';

export interface ProviderSpec {
  id: ProviderId;
  label: string;
  endpoint: string;
  /** Where the user gets a key. */
  keysUrl: string;
  defaultModel: string;
  /** Suggestions offered in a datalist; the field stays free text. */
  modelSuggestions: string[];
  /** Shown under the key field. */
  keyHint: string;
  /** Shown under the model field. Separate on purpose, they are different questions. */
  modelHint: string;
  /** Whether this provider takes OpenRouter's `reasoning` request parameter. */
  supportsReasoning?: boolean;
  /**
   * Runs on the reader's own machine and wants no key at all.
   *
   * Worth its own flag rather than an empty-string special case, because the
   * key check is what decides whether the adapter is available, and a local
   * model with no key is available in every sense that matters.
   */
  keyless?: boolean;
  /**
   * Where to ask the key what it can actually reach.
   *
   * Hardcoding model names was a mistake with a delayed fuse: the list is
   * right on the day it is written and silently wrong months later, and the
   * reader discovers it as a 404 they cannot act on. Providers retire names,
   * and some are withheld from new accounts entirely, so the only reliable
   * answer to "which model should I use" comes from the account itself.
   */
  listUrl?: string;
}

/**
 * One turn of a follow-up conversation.
 *
 * `reasoningDetails` exists because OpenRouter is explicit that, when
 * reasoning is enabled, the blocks must be passed back **completely
 * unmodified**. "the entire sequence of consecutive reasoning blocks must
 * match the outputs generated by the model during the original request; you
 * cannot rearrange or modify the sequence." So it is carried as an opaque
 * value: never parsed, never reshaped, never merged.
 */
export interface Turn {
  role: 'user' | 'assistant';
  content: string;
  reasoningDetails?: unknown;
}

export interface AskResult {
  text: string;
  /** Opaque. Store it and hand it straight back on the next turn. */
  reasoningDetails?: unknown;
}

